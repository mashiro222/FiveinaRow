import fs from 'node:fs/promises';
import {OPENINGS} from '../src/openings.js';
import {selectVariations,SELECTION} from './opening-selection.mjs';
const report=JSON.parse(await fs.readFile('reports/opening-analysis.json','utf8'));
let extra={positions:{}};try{extra=JSON.parse(await fs.readFile('reports/opening-extra-analysis.json','utf8'));}catch(e){if(e.code!=='ENOENT')throw e;}
const library={schema:1,engineId:report.engineId,sourceCommit:report.sourceCommit,networksCommit:report.networksCommit,generatedAt:report.createdAt,settings:report.settings,selection:SELECTION,openings:{}};
for(const o of OPENINGS){
 const rules={};
 for(const rule of ['renju','freestyle']){
  const result=report.positions[`${o.code}:${rule}`];if(!result)continue;
  if(JSON.stringify(result.moves)!==JSON.stringify(o.moves))throw new Error(`Opening mismatch: ${o.code}`);
  const variations=selectVariations(result,extra.positions[`${o.code}:${rule}`]||[]);
  rules[rule]={depth:result.candidates[0].depth,elapsedMs:result.elapsedMs,variations};
 }
 library.openings[o.code]=rules;
}
await fs.writeFile('src/opening-lines.js','// Generated by scripts/analyze-openings.mjs and build-opening-lines.mjs. Do not hand-edit.\nexport const OPENING_ANALYSIS = '+JSON.stringify(library,null,2)+';\n');
console.log(JSON.stringify({positions:Object.keys(report.positions).length,counts:Object.fromEntries(OPENINGS.map(o=>[o.name,Object.fromEntries(Object.entries(library.openings[o.code]).map(([r,d])=>[r,d.variations.length]))]))},null,2));
